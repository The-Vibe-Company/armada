import { HARNESSES } from "@armada/core";
import { modalFailureReceipt } from "./errors.ts";
import type { ModalResourceReceipt } from "./ports.ts";
import type { ModalProvider } from "./provider.ts";
import { type GoldenSshRecipe, probeModalSsh } from "./ssh-probe.ts";

/** Opt-in, billable real-cloud probe. Compose server/ingest first, then invoke explicitly.
 * No environment/profile/credential-file reads and no secret diagnostics. Credentials belong solely
 * to the injected server resolver. On any checkpoint uncertainty the live source is preserved.
 */
export async function runModalConformance(
  provider: ModalProvider,
  options: {
    /** Generated by current production core; required for full golden build/scanner acceptance. */
    goldenRecipe?: GoldenSshRecipe & { scanCommand: string };
    models: boolean;
    launchEnv?: Record<string, string>;
    pollMs?: number;
    onReceipt?: (receipt: ModalResourceReceipt) => void | Promise<void>;
  },
): Promise<{ checks: string[]; preservedSandboxIds: string[] }> {
  const checks: string[] = [];
  const preservedSandboxIds: string[] = [];
  const suffix = crypto.randomUUID();
  let builder: string | undefined;
  let fork: string | undefined;
  let stopped = false;
  let snapshot = `conformance-${suffix}`;
  const seedSnapshot = snapshot;
  try {
    try {
      builder = (await provider.createGolden({ name: snapshot, idempotencyKey: `builder-${suffix}`, ttlSeconds: 3600 }))
        .id;
    } catch (error) {
      const receipt = modalFailureReceipt(error);
      if (receipt) {
        builder = receipt.sandboxId;
        await options.onReceipt?.(receipt);
      }
      throw error;
    }
    const exec = await provider.exec({
      sandboxId: builder,
      command:
        "test -d /home/user/repos && git --version && gh --version && bun --version && claude --version && codex --version",
      timeoutSeconds: 60,
    });
    if (exec.detached || exec.exitCode !== 0) throw Error("toolchain_conformance_failed");
    checks.push("logical create / pinned installed toolchain / protected runner exec");
    await probeModalSsh(provider, builder);
    checks.push("real ephemeral SSH authentication / strict pinned host key");
    if (options.goldenRecipe) {
      await probeModalSsh(provider, builder, options.goldenRecipe);
      const scanned = await provider.exec({
        sandboxId: builder,
        command: options.goldenRecipe.scanCommand,
        cwd: "/home/user",
        timeoutSeconds: 600,
      });
      if (scanned.detached || scanned.exitCode !== 0) throw Error("production_golden_scan_failed");
      checks.push("production SSH golden baseline / privileged scanner");
    }
    const seed = await provider.exec({
      sandboxId: builder,
      command: "printf disposable-builder-history > /home/user/.armada-runtime/golden-history-marker",
      timeoutSeconds: 30,
    });
    if (seed.detached || seed.exitCode !== 0) throw Error("golden_history_probe_setup_failed");
    try {
      await provider.snapshot({ sandboxId: builder, name: snapshot });
    } catch (error) {
      const receipt = modalFailureReceipt(error);
      if (receipt) await options.onReceipt?.(receipt);
      preservedSandboxIds.push(builder);
      throw Error(`snapshot_uncertain_source_preserved:${builder}`);
    }
    // Mirrors canonical NULL master after secure-create retention: no ordinary worker clone.
    await provider.delete({ sandboxId: builder });
    try {
      builder = (await provider.restoreGoldenMaster({ snapshotId: snapshot })).id;
    } catch (error) {
      const receipt = modalFailureReceipt(error);
      if (receipt) {
        builder = receipt.sandboxId;
        await options.onReceipt?.(receipt);
      }
      throw error;
    }
    const edited = await provider.exec({
      sandboxId: builder,
      command:
        "test ! -e /home/user/.armada-runtime/golden-history-marker && test ! -d /home/user/.armada-runtime/session-state && printf edited-golden > /home/user/golden-restore-marker",
      timeoutSeconds: 30,
    });
    if (edited.detached || edited.exitCode !== 0) throw Error("golden_restore_history_not_clean");
    const beforeReconnect = await provider.get(builder);
    const reconnected = await provider.restoreGoldenMaster({ snapshotId: snapshot });
    if (reconnected.id !== builder || reconnected.physicalGeneration !== beforeReconnect.physicalGeneration)
      throw Error("golden_reconnect_not_idempotent");
    snapshot = `conformance-connected-${suffix}`;
    try {
      await provider.snapshot({ sandboxId: builder, name: snapshot });
    } catch (error) {
      const receipt = modalFailureReceipt(error);
      if (receipt) await options.onReceipt?.(receipt);
      preservedSandboxIds.push(builder);
      throw Error(`snapshot_uncertain_source_preserved:${builder}`);
    }
    await provider.delete({ sandboxId: builder });
    await provider.deleteSnapshot(seedSnapshot);
    checks.push("NULL-master golden restore / clean history / idempotent reconnect / edit-resnapshot");
    try {
      fork = (
        await provider.fork({
          from: snapshot,
          name: `fork-${suffix}`,
          idempotencyKey: `fork-${suffix}`,
          env: options.launchEnv ?? {},
          ttlSeconds: 3600,
        })
      ).id;
    } catch (error) {
      const receipt = modalFailureReceipt(error);
      if (receipt) {
        fork = receipt.sandboxId;
        await options.onReceipt?.(receipt);
      }
      throw error;
    }
    const marker = await provider.exec({
      sandboxId: fork,
      command:
        "test $(cat /home/user/golden-restore-marker) = edited-golden && test ! -d /home/user/.armada-runtime/session-state && printf checkpoint-marker > /home/user/marker && test ! -e /run/armada-ssh/host && test ! -e /run/armada-ssh/authorized_keys",
      timeoutSeconds: 30,
    });
    if (marker.detached || marker.exitCode !== 0) throw Error("golden_ssh_scrub_failed");
    checks.push("golden SSH scrub / independent fork");
    const turns = [];
    if (options.models) {
      const receipts = await Promise.all(
        HARNESSES.map((harness) =>
          provider.prompt({ sandboxId: fork as string, harness, text: "Reply with exactly: armada-conformance-ok" }),
        ),
      );
      for (const receipt of receipts) {
        for (let i = 0; i < 600; i++) {
          const state = await provider.getPrompt({ sandboxId: fork, promptId: receipt.promptId });
          if (state.done) {
            if (state.status !== "finished") throw Error("model_turn_failed");
            break;
          }
          if (i === 599) throw Error("model_turn_timeout");
          await Bun.sleep(options.pollMs ?? 250);
        }
        turns.push(receipt);
      }
      checks.push("real concurrent Claude and Codex sessions");
    }
    try {
      await provider.stop({ sandboxId: fork });
      stopped = true;
    } catch {
      preservedSandboxIds.push(fork);
      throw Error(`checkpoint_uncertain_source_preserved:${fork}`);
    }
    const restored = await provider.exec({
      sandboxId: fork,
      command: "test $(cat /home/user/marker) = checkpoint-marker",
      timeoutSeconds: 30,
    });
    stopped = false;
    if (restored.detached || restored.exitCode !== 0) throw Error("restore_marker_missing");
    checks.push("checkpoint / durable save / same logical ID restore");
    for (const [index, receipt] of turns.entries()) {
      const next = await provider.prompt({
        sandboxId: fork,
        harness: index === 0 ? "claude" : "codex",
        conversationId: receipt.conversationId,
        text: "Reply with exactly: resumed-ok",
      });
      if (next.conversationId !== receipt.conversationId) throw Error("conversation_identity_changed");
      for (let i = 0; i < 600; i++) {
        const state = await provider.getPrompt({ sandboxId: fork, promptId: next.promptId });
        if (state.done) {
          if (state.status !== "finished") throw Error("resume_failed");
          break;
        }
        if (i === 599) throw Error("resume_timeout");
        await Bun.sleep(options.pollMs ?? 250);
      }
    }
    if (turns.length) checks.push("both real model conversations resume after restore");
    const before = await provider.events({ sandboxId: fork });
    await provider.deleteSnapshot(snapshot);
    checks.push("snapshot logical deletion with live fork");
    await provider.delete({ sandboxId: fork });
    const after = await provider.events({ sandboxId: fork });
    if (JSON.stringify(before.events) !== JSON.stringify(after.events)) throw Error("deleted_event_history_changed");
    checks.push("durable events after delete / last-fork image GC");
    fork = undefined;
    return { checks, preservedSandboxIds };
  } finally {
    try {
      if (fork && !preservedSandboxIds.includes(fork)) {
        // Never destroy a source whose checkpoint may be unresolved, even on an unrelated probe failure.
        const receipt = (await provider.resourceReceipts()).find((x) => x.sandboxId === fork);
        if (receipt) await options.onReceipt?.(receipt);
        if (receipt && ["checkpoint", "snapshot", "terminate"].includes(receipt.phase)) preservedSandboxIds.push(fork);
        else if (stopped || receipt) await provider.delete({ sandboxId: fork });
      }
      if (builder && !preservedSandboxIds.includes(builder)) {
        const info = await provider.get(builder).catch(() => undefined);
        if (info?.providerState !== "snapshot") await provider.delete({ sandboxId: builder });
      }
      if (!preservedSandboxIds.length) {
        await provider.deleteSnapshot(snapshot).catch(() => {});
        if (seedSnapshot !== snapshot) await provider.deleteSnapshot(seedSnapshot).catch(() => {});
      }
    } finally {
      for (const receipt of await provider.resourceReceipts().catch(() => [])) await options.onReceipt?.(receipt);
    }
  }
}
