import { HARNESS_CATALOG, HARNESSES } from "../packages/core/src/harnesses.ts";

const target = new URL("../apps/ios/Armada/Model/Harness.generated.swift", import.meta.url);
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: bun scripts/generate-ios-harness.ts [--check]");
}

function swiftString(value: string): string {
  return `"${value
    .replaceAll("\\", "\\\\")
    .replaceAll('"', '\\"')
    .replaceAll("\n", "\\n")
    .replaceAll("\r", "\\r")
    .replaceAll("\t", "\\t")}"`;
}

for (const harness of HARNESSES) {
  if (!/^[a-z][a-z0-9_]*$/.test(harness)) throw new Error("Harness IDs must be Swift enum identifiers.");
}

const output = `// Generated by bun scripts/generate-ios-harness.ts. Do not edit.
// Source: packages/core/src/harnesses.ts. IDs, labels and steering match the server catalog.
enum Harness: String, CaseIterable, Identifiable, Hashable, Sendable {
${HARNESSES.map((id) => `    case \`${id}\``).join("\n")}

    var id: String { rawValue }

    var label: String {
        switch self {
${HARNESSES.map((id) => `        case .\`${id}\`: ${swiftString(HARNESS_CATALOG[id].label)}`).join("\n")}
        }
    }

    /// Only the wording depends on this capability; the server decides how steering runs.
    var steerRestartsTurn: Bool {
        switch self {
${HARNESSES.map((id) => `        case .\`${id}\`: ${HARNESS_CATALOG[id].capabilities.steer === "restart"}`).join("\n")}
        }
    }
}
`;

if (args[0] === "--check") {
  if (!(await Bun.file(target).exists()) || (await Bun.file(target).text()) !== output) {
    throw new Error("iOS harness metadata is stale. Run bun scripts/generate-ios-harness.ts and commit the result.");
  }
} else {
  await Bun.write(target, output);
  console.log("Wrote apps/ios/Armada/Model/Harness.generated.swift");
}
