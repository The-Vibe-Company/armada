// Build-time discovery only. Runtime configuration never resolves or imports code.
import { randomUUID } from "node:crypto";
import { readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const plugins = join(root, "packages/plugins");
const output = join(root, "packages/daemon/src/plugins/catalog.generated.ts");
const entries: string[] = [];
for (const dir of (await readdir(plugins, { withFileTypes: true })).sort((a, b) => a.name.localeCompare(b.name))) {
  if (!dir.isDirectory()) continue;
  const directory = join(plugins, dir.name);
  const pkg = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
  let manifest: unknown = pkg.armada;
  try {
    manifest = JSON.parse(await readFile(join(directory, "armada-plugin.json"), "utf8"));
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
  }
  const exports = typeof pkg.exports === "object" ? (pkg.exports?.["."] ?? pkg.exports) : pkg.exports;
  const entry =
    (typeof exports === "object" ? (exports?.import ?? exports?.default) : exports) ?? pkg.main ?? "index.js";
  if (typeof entry !== "string") throw new Error(`${dir.name}: module entry must be a string`);
  const modulePath = resolve(directory, entry);
  if (!modulePath.startsWith(`${directory}${sep}`))
    throw new Error(`${dir.name}: module entry must be inside its package`);
  const specifier = relative(dirname(output), modulePath).split(sep).join("/");
  entries.push(
    `  { id: ${JSON.stringify(dir.name)}, manifest: ${JSON.stringify(manifest ?? null)}, load: () => import(${JSON.stringify(specifier)}) }`,
  );
}
const temporary = `${output}.${randomUUID()}.tmp`;
try {
  await writeFile(
    temporary,
    `// Generated by scripts/plugin-catalog.ts. Do not edit.\nimport type { PluginCatalogEntry } from "./catalog.ts";\n\nexport const BUNDLED_PLUGINS: readonly PluginCatalogEntry[] = [\n${entries.join(",\n")}\n];\n`,
  );

  await rename(temporary, output);
} finally {
  await rm(temporary, { force: true });
}
