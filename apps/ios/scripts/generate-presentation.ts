import { describeSandboxFailure } from "../../../packages/core/src/native-failure.ts";

// Keep Swift's closed public diagnoses aligned with the dashboard's shared mapper.
const reasons = new Set<string>();
for (const path of ["native-failure.ts", "runtime-startup-failure.ts", "docker-api.ts"]) {
  const source = await Bun.file(new URL(`../../../packages/core/src/${path}`, import.meta.url)).text();
  for (const match of source.matchAll(/"([^"\n]*)"/g)) reasons.add(match[1]!);
  for (const match of source.matchAll(/^ {2}([a-z_]+): \{/gm)) reasons.add(match[1]!);
}
for (const code of [...reasons]) {
  for (const phase of [
    "authentication",
    "session_restore",
    "model_selection",
    "session_start",
    "turn_start",
    "initialization",
  ]) {
    reasons.add(`${code}:${phase}`);
  }
}
for (const reason of [...reasons]) {
  const help = describeSandboxFailure(reason);
  reasons.add(`${help.title}. ${help.hint}`);
}
const fallback = describeSandboxFailure(null);
const text = (reason: string | null) => {
  const help = describeSandboxFailure(reason);
  return `${help.title}. ${help.hint}`;
};
const quote = (value: string) => JSON.stringify(value);
const entries = [...reasons].sort().filter((reason) => describeSandboxFailure(reason).title !== fallback.title);
const output = `// Generated by bun apps/ios/scripts/generate-presentation.ts. Do not edit.
// Source: core's describeSandboxFailure, also used by the dashboard.
public enum SandboxPresentation {
    public static func sandboxFailure(_ reason: String?) -> String {
        guard let reason else { return ${quote(text(null))} }
        return failures[reason] ?? ${quote(text(null))}
    }

    public static func interruption(_ reason: String?) -> String {
        switch reason {
        case "interrupted_by_provider_move": "The sandbox moved to a new machine. Send the prompt again."
        case "interrupted_by_harness_exit": "Send the prompt again to start a fresh agent process."
        default: "The turn was interrupted. Check the conversation, then send the prompt again when the sandbox is available."
        }
    }

    private static let failures: [String: String] = [
${entries.map((reason) => `        ${quote(reason)}: ${quote(text(reason))},`).join("\n")}
    ]
}
`;
const target = new URL("../ArmadaKit/Sources/ArmadaKit/SandboxPresentation.generated.swift", import.meta.url);
if (process.argv.includes("--check")) {
  if (!(await Bun.file(target).exists()) || (await Bun.file(target).text()) !== output) {
    throw new Error("iOS presentation is stale. Run bun apps/ios/scripts/generate-presentation.ts");
  }
} else {
  await Bun.write(target, output);
}
